    #[test]
    fn parse_быба() {
        let parsed = MessageEntityRef::parse(
            "быба",
            &[
                MessageEntity { kind: Strikethrough, offset: 0, length: 1 },
                MessageEntity { kind: Bold, offset: 1, length: 1 },
                MessageEntity { kind: Italic, offset: 2, length: 1 },
                MessageEntity { kind: Code, offset: 3, length: 1 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "б" && entity.kind() == &Strikethrough, entity if entity.text() == "ы" && entity.kind() == &Bold, entity if entity.text() == "б" && entity.kind() == &Italic, entity if entity.text() == "а" && entity.kind() == &Code]
        );
    }

    #[test]
    fn parse_symbol_24bit() {
        let parsed = MessageEntityRef::parse(
            "xx আ #tt",
            &[MessageEntity { kind: Hashtag, offset: 5, length: 3 }],
        );

        assert_matches!(parsed, [entity if entity.text() == "#tt" && entity.kind() == &Hashtag]);
    }

    #[test]
    fn parse_enclosed() {
        let parsed = MessageEntityRef::parse(
            "b i b",
            // For some reason this is how telegram encodes <b>b <i>i<i/> b<b/>
            &[
                MessageEntity { kind: Bold, offset: 0, length: 2 },
                MessageEntity { kind: Bold, offset: 2, length: 3 },
                MessageEntity { kind: Italic, offset: 2, length: 1 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "b " && entity.kind() == &Bold, entity if entity.text() == "i b" && entity.kind() == &Bold, entity if entity.text() == "i" && entity.kind() == &Italic]
        );
    }

    #[test]
    fn parse_nothing() {
        let parsed = MessageEntityRef::parse("a", &[]);
        assert_eq!(parsed, []);
    }

    #[test]
    fn parse_empty() {
        // It should be impossible for this to be returned from telegram, but just to be
        // sure
        let parsed = MessageEntityRef::parse(
            "",
            &[
                MessageEntity { kind: Bold, offset: 0, length: 0 },
                MessageEntity { kind: Italic, offset: 0, length: 0 },
            ],
        );

        assert_matches!(
            parsed,
            [entity if entity.text() == "" && entity.kind() == &Bold, entity if entity.text() == "" && entity.kind() == &Italic]
        );
    }

    #[test]
    fn date_time() {
        let unix_time = chrono::DateTime::from_timestamp(1_700_000_000, 0).unwrap();
        let entity = MessageEntity::date_time(unix_time, Some(String::from("wDT")), 5, 10);
        let json = r#"{"type":"date_time","offset":5,"length":10,"unix_time":1700000000,"date_time_format":"wDT"}"#;

        assert_eq!(entity, serde_json::from_str::<MessageEntity>(json).unwrap());
        assert_eq!(
            serde_json::to_value(&entity).unwrap(),
            serde_json::from_str::<serde_json::Value>(json).unwrap()
        );
    }

    #[test]
    fn date_time_without_format() {
        let unix_time = chrono::DateTime::from_timestamp(1_700_000_000, 0).unwrap();
        let entity = MessageEntity::date_time(unix_time, None, 0, 12);
        let json = r#"{"type":"date_time","offset":0,"length":12,"unix_time":1700000000}"#;

        assert_eq!(entity, serde_json::from_str::<MessageEntity>(json).unwrap());
        let serialized = serde_json::to_string(&entity).unwrap();
        assert_eq!(serialized.find("date_time_format"), None);
        assert_eq!(entity, serde_json::from_str::<MessageEntity>(&serialized).unwrap());
    }

    #[test]
    fn parse_date_time_utf16() {
        let unix_time = chrono::DateTime::from_timestamp(1_772_366_400, 0).unwrap();
        let text = "📅 Event: 2026-03-01 12:00";
        // 📅 takes 2 UTF-16 code units, " Event: " takes 8 => offset 10, length 16
        let entities = [MessageEntity::date_time(unix_time, Some(String::from("DT")), 10, 16)];
        let parsed = MessageEntityRef::parse(text, &entities);

        assert_matches!(
            parsed,
            [entity if entity.text() == "2026-03-01 12:00"
                && matches!(
                    entity.kind(),
                    MessageEntityKind::DateTime {
                        unix_time: parsed_time,
                        date_time_format: Some(fmt),
                    } if *parsed_time == unix_time && fmt == "DT"
                )]
        );
    }

